"""Generate the primary audit tables and appendix detail tables from summaries.

The script intentionally consumes summary JSON rather than raw experiment
records.  Validation of raw records belongs to the corresponding summarizers;
this final stage checks the summary gates needed by the paper and performs only
deterministic formatting.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Dict, List, Mapping, Sequence, Tuple


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_RESPONSE = PROJECT_ROOT / "results" / "response_summary.json"
DEFAULT_ASLORA = PROJECT_ROOT / "results" / "aslora_summary.json"
DEFAULT_ROUTER = PROJECT_ROOT / "results" / "router_decisions_summary.json"
DEFAULT_OUTPUT_DIR = PROJECT_ROOT / "paper" / "generated"
PRIMARY_SEEDS = (0, 1, 2)
RELEASE_SUMMARY_LABELS = {
    "response_summary.json": "results/response_summary.json",
    "aslora_summary.json": "results/aslora_summary.json",
    "router_decisions_summary.json": "results/router_decisions_summary.json",
}


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def _mapping(value: object, name: str) -> Mapping[str, object]:
    _require(isinstance(value, dict), "%s must be an object" % name)
    return value


def _rows(value: object, name: str) -> Sequence[Mapping[str, object]]:
    _require(isinstance(value, list), "%s must be an array" % name)
    output = []
    for index, item in enumerate(value):
        output.append(_mapping(item, "%s[%d]" % (name, index)))
    return output


def _finite(value: object, name: str) -> float:
    result = float(value)
    _require(math.isfinite(result), "%s must be finite" % name)
    return result


def _load(path: Path) -> Mapping[str, object]:
    payload = json.loads(path.read_text(encoding="utf-8"))
    return _mapping(payload, str(path))


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _scientific(value: object, digits: int = 2) -> str:
    number = _finite(value, "scientific value")
    if number == 0.0:
        return "$0$"
    exponent = int(math.floor(math.log10(abs(number))))
    mantissa = number / (10.0 ** exponent)
    return "$%.*f\\!\\times\\!10^{%d}$" % (digits, mantissa, exponent)


def _signed(value: object, digits: int = 4) -> str:
    return ("%+.*f" % (digits, _finite(value, "signed value")))


def _interval(record: object, digits: int = 4) -> str:
    bounds = _mapping(record, "interval")
    return "$[%s,%s]$" % (
        _signed(bounds.get("min"), digits),
        _signed(bounds.get("max"), digits),
    )


def _action_tex(action_key: object) -> str:
    pieces = []
    for item in str(action_key).split("|"):
        target, pair = item.split(":", 1)
        lower, upper = pair.split("-", 1)
        symbol = "Q" if target == "query" else "V"
        pieces.append("%s:%s\\leftarrow%s" % (symbol, lower, upper))
    return "$%s$" % ";\\,".join(pieces)


def _header(source_path: Path) -> List[str]:
    # Verification deliberately rebuilds summaries outside their canonical
    # directory.  Embed the logical release source rather than the transient
    # filesystem location so byte-identical inputs yield byte-identical tables.
    source_label = RELEASE_SUMMARY_LABELS.get(source_path.name, source_path.name)
    return [
        "% Auto-generated by experiments/generate_paper_audit_tables.py; do not edit.",
        f"% Source: {source_label}",
        f"% Source SHA256: {_sha256(source_path)}",
    ]


def response_table(summary: Mapping[str, object], source_path: Path) -> str:
    protocol = _mapping(summary.get("protocol"), "response.protocol")
    aggregate = _mapping(summary.get("across_seed"), "response.across_seed")
    rows = sorted(
        _rows(summary.get("seed_rows"), "response.seed_rows"),
        key=lambda row: int(row.get("seed", -1)),
    )
    _require(
        tuple(int(row.get("seed", -1)) for row in rows) == PRIMARY_SEEDS,
        "response summary must contain seeds 0, 1, and 2",
    )
    _require(
        protocol.get("seeds") == list(PRIMARY_SEEDS)
        and int(protocol.get("probes_per_seed", -1)) == 8
        and _finite(protocol.get("fixed_gauge_strength"), "gauge strength") == 0.35,
        "response summary protocol drifted",
    )
    required_flags = (
        "all_fixed_nonpermutation_probes_detected",
        "all_formula_checks_pass",
        "all_permutation_controls_pass",
        "all_rank_assumptions_pass",
    )
    _require(
        all(aggregate.get(flag) is True for flag in required_flags),
        "response summary failed a required control",
    )
    probe_total = sum(int(row.get("detected_probes", -1)) for row in rows)
    probe_expected = sum(int(row.get("probe_count", -1)) for row in rows)
    _require(probe_total == probe_expected, "not every fixed response probe detected")
    formula_max = max(
        _finite(row.get("formula_worst_fd_relative_error"), "worst-chart FD error")
        for row in rows
    )
    _require(
        math.isclose(
            formula_max,
            _finite(
                aggregate.get("maximum_formula_fd_relative_error"),
                "aggregate worst-chart FD error",
            ),
            rel_tol=0.0,
            abs_tol=0.0,
        ),
        "response formula aggregate is inconsistent with seed rows",
    )
    permutation_max = max(
        _finite(row.get("permutation_max_relative_response_difference"), "control")
        for row in rows
    )
    medians = [
        _finite(row.get("nonpermutation_median_relative_response_difference"), "median")
        for row in rows
    ]

    lines = _header(source_path)
    lines.extend(
        [
            "\\providecommand{\\ResponseProbeDetected}{%d}" % probe_total,
            "\\providecommand{\\ResponseProbeExpected}{%d}" % probe_expected,
            "\\providecommand{\\ResponseEffectiveMax}{\\ensuremath{%s}}"
            % _scientific(aggregate.get("maximum_effective_relative_l2_error")).strip("$"),
            "\\providecommand{\\ResponseFormulaMax}{\\ensuremath{%s}}"
            % _scientific(formula_max).strip("$"),
            "\\providecommand{\\ResponsePermutationMax}{\\ensuremath{%s}}"
            % _scientific(permutation_max).strip("$"),
            "\\providecommand{\\ResponseMedianMin}{%.4f}" % min(medians),
            "\\providecommand{\\ResponseMedianMax}{%.4f}" % max(medians),
            "\\begin{table}[H]",
            "\\centering",
            "\\scriptsize",
            "\\caption{Frozen-checkpoint response audit.  The effective-product column checks the fixed non-permutation gauge; $\\Delta\\mathcal R$ compares Euclidean instantaneous response operators on fixed Gaussian effective-gradient probes.  The permutation column is the label-swap control.}",
            "\\label{tab:response-audit}",
            "\\resizebox{\\linewidth}{!}{%",
            "\\begin{tabular}{crrrrrrr}",
            "\\toprule",
            "Seed & Effective product rel. error & $\\min A$ & $\\sigma_{\\min}(A)$ & $\\sigma_{\\min}(B)$ & Perm. max rel. $\\Delta\\mathcal R$ & Nonperm. median rel. $\\Delta\\mathcal R$ & Detected probes \\\\",
            "\\midrule",
        ]
    )
    for row in rows:
        lines.append(
            "%d & %s & %s & %.4f & %.3f & %s & %.4f & %d/%d \\\\"
            % (
                int(row["seed"]),
                _scientific(row["effective_relative_l2_error"]),
                _scientific(row["minimum_A_entry"]),
                _finite(row["A_sigma_min"], "A sigma"),
                _finite(row["B_sigma_min"], "B sigma"),
                _scientific(row["permutation_max_relative_response_difference"]),
                _finite(row["nonpermutation_median_relative_response_difference"], "median"),
                int(row["detected_probes"]),
                int(row["probe_count"]),
            )
        )
    lines.extend(["\\bottomrule", "\\end{tabular}%", "}", "\\end{table}"])
    return "\n".join(lines) + "\n"


def aslora_table(summary: Mapping[str, object], source_path: Path) -> str:
    _require(
        summary.get("format") == "aslora-three-seed-first-merge-summary-v1",
        "wrong ASLoRA summary format",
    )
    protocol = _mapping(summary.get("protocol"), "aslora.protocol")
    validation = _mapping(summary.get("validation"), "aslora.validation")
    chain = _mapping(summary.get("chain_assessment"), "aslora.chain")
    _require(
        protocol.get("seeds") == list(PRIMARY_SEEDS)
        and int(protocol.get("gauge_count_per_seed", -1)) == 10
        and protocol.get("cross_seed_protocol_hash_pass") is True,
        "ASLoRA summary protocol drifted",
    )
    _require(
        validation.get("candidate_coverage_all_pass") is True
        and validation.get("canonical_scientific_gate_all_pass") is True
        and validation.get("fully_attested_reproducibility_gate") is True,
        "ASLoRA summary failed coverage, equivalence, restoration, or source gates",
    )
    _require(
        chain.get(
            "primary_per_projection_chain_holds_for_both_candidate_modes_in_all_three_seeds"
        )
        is True,
        "ASLoRA primary three-seed chain did not hold",
    )
    aggregates = _rows(
        summary.get("across_seed_mode_scope"), "aslora.across_seed_mode_scope"
    )
    _require(len(aggregates) == 4, "ASLoRA summary needs four mode/scope cells")
    seed_rows = _rows(summary.get("seed_mode_scope_rows"), "aslora.seed rows")
    primary_rows = sorted(
        [row for row in seed_rows if row.get("decision_scope") == "per_projection"],
        key=lambda row: (int(row["seed"]), 0 if row["candidate_mode"] == "adjacent" else 1),
    )
    _require(len(primary_rows) == 6, "ASLoRA summary needs six primary rows")

    aggregate_index = {
        (str(row["candidate_mode"]), str(row["decision_scope"])): row
        for row in aggregates
    }

    lines = _header(source_path)
    lines.extend(
        [
            "\\providecommand{\\ASLORAAdjacentPrimaryChanges}{%d}"
            % int(aggregate_index[("adjacent", "per_projection")]["total_action_change_count"]),
            "\\providecommand{\\ASLORAAllPrimaryChanges}{%d}"
            % int(aggregate_index[("all", "per_projection")]["total_action_change_count"]),
            "\\providecommand{\\ASLORATotalGaugeInstances}{%d}"
            % int(aggregate_index[("all", "per_projection")]["total_gauge_instances"]),
            "\\providecommand{\\ASLORAGaugesPerSeed}{%d}"
            % int(protocol["gauge_count_per_seed"]),
            "\\begin{table}[H]",
            "\\centering",
            "\\small",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\caption{ASLoRA first-merge decision audit over \\ASLORAGaugesPerSeed{} gauges per seed.  Changes are relative to the identity-gauge raw-running-$B$ action.  The loss interval is the canonical validation difference (selected action minus identity action), not a gauged float32 re-execution; accuracy and F1 intervals are in Appendix Table~\\ref{tab:aslora-metric-details}.  The chain column requires a changed action with a nonzero validation consequence in every seed.}",
            "\\label{tab:aslora-chain}",
            "\\begin{tabular}{@{}llcrrcc@{}}",
            "\\toprule",
            "Candidates & Scope & By seed & Changed & Seeds & $\\Delta$ loss & Chain \\\\",
            "\\midrule",
        ]
    )
    for mode in ("adjacent", "all"):
        for scope in ("per_projection", "joint"):
            row = aggregate_index[(mode, scope)]
            counts = _mapping(row["action_change_counts_by_seed"], "change counts")
            delta = _mapping(row["delta_from_seed_identity_action"], "metric deltas")
            lines.append(
                "%s & %s & $(%d,%d,%d)$ & %d/%d & %d/3 & %s & %s \\\\"
                % (
                    "Adjacent" if mode == "adjacent" else "All pairs",
                    "per-proj." if scope == "per_projection" else "joint pair",
                    int(counts["0"]),
                    int(counts["1"]),
                    int(counts["2"]),
                    int(row["total_action_change_count"]),
                    int(row["total_gauge_instances"]),
                    int(row["seeds_with_action_change"]),
                    _interval(delta["loss"]),
                    "yes" if row["chain_holds_in_all_three_seeds"] else "no",
                )
            )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines) + "\n"


def aslora_metric_detail_table(
    summary: Mapping[str, object], source_path: Path
) -> str:
    """Format accuracy/F1 intervals moved out of the readable main table."""

    # Keep one validation path for the primary and detail renderings.
    aslora_table(summary, source_path)
    aggregates = _rows(
        summary.get("across_seed_mode_scope"), "aslora.across_seed_mode_scope"
    )
    aggregate_index = {
        (str(row["candidate_mode"]), str(row["decision_scope"])): row
        for row in aggregates
    }

    lines = _header(source_path)
    lines.extend(
        [
            "\\begin{table}[H]",
            "\\centering",
            "\\small",
            "\\caption{Canonical validation accuracy and F1 differences for the four ASLoRA candidate/scope cells in Table~\\ref{tab:aslora-chain}.  Intervals range over all 30 selected gauge actions in each cell, including unchanged selections, and are selected-action minus identity-action differences.}",
            "\\label{tab:aslora-metric-details}",
            "\\begin{tabular}{@{}llcc@{}}",
            "\\toprule",
            "Candidates & Scope & $\\Delta$ accuracy & $\\Delta$ F1 \\\\",
            "\\midrule",
        ]
    )
    for mode in ("adjacent", "all"):
        for scope in ("per_projection", "joint"):
            row = aggregate_index[(mode, scope)]
            delta = _mapping(row["delta_from_seed_identity_action"], "metric deltas")
            lines.append(
                "%s & %s & %s & %s \\\\"
                % (
                    "Adjacent" if mode == "adjacent" else "All pairs",
                    "per-projection" if scope == "per_projection" else "joint pair",
                    _interval(delta["accuracy"]),
                    _interval(delta["f1"]),
                )
            )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines) + "\n"


def aslora_baseline_table(summary: Mapping[str, object], source_path: Path) -> str:
    """Format secondary alternatives subject to the primary ASLoRA gates."""

    # Reuse the primary formatter as the single validation path.  Its output is
    # discarded here; failure of any scientific or attestation gate still
    # prevents the appendix table from being generated.
    aslora_table(summary, source_path)
    seed_rows = _rows(summary.get("seed_mode_scope_rows"), "aslora.seed rows")
    primary_rows = sorted(
        [row for row in seed_rows if row.get("decision_scope") == "per_projection"],
        key=lambda row: (
            int(row["seed"]),
            0 if row["candidate_mode"] == "adjacent" else 1,
        ),
    )
    _require(len(primary_rows) == 6, "ASLoRA summary needs six primary rows")

    def loss_delta_sign_counts(method: str) -> Tuple[int, int, int]:
        values = []
        for row in primary_rows:
            baselines = _mapping(row["baselines"], "ASLoRA baselines")
            baseline = _mapping(baselines[method], method)
            deltas = _mapping(
                baseline.get("delta_from_raw_B_action"), "%s loss deltas" % method
            )
            values.append(_finite(deltas.get("loss"), "%s loss delta" % method))
        return (
            sum(value < 0.0 for value in values),
            sum(value > 0.0 for value in values),
            sum(value == 0.0 for value in values),
        )

    effective_signs = loss_delta_sign_counts(
        "gauge_invariant_current_effective_baseline"
    )
    activation_signs = loss_delta_sign_counts(
        "gauge_invariant_current_local_activation_baseline"
    )

    def stacked_action(action: str, suffix: str = "") -> str:
        parts = _action_tex(action).strip("$").split(r";\,")
        rows = ["$" + part + "$" for part in parts]
        if suffix:
            rows.append(suffix)
        return r"\shortstack[l]{" + r"\\".join(rows) + "}"

    def action_with_loss_delta(value: object, name: str) -> str:
        baseline = _mapping(value, name)
        deltas = _mapping(
            baseline.get("delta_from_raw_B_action"), "%s loss deltas" % name
        )
        return stacked_action(baseline["action_key"],
                              "$\\Delta L=%s$" % _signed(deltas.get("loss")))

    lines = _header(source_path)
    lines.extend(
        [
            "\\begin{table}[H]",
            "\\centering",
            "\\small",
            "\\caption{Declared alternatives for the primary per-projection ASLoRA decision.  Effective-update and local-activation rules are gauge invariant.  Their cells give the selected action and canonical validation-loss difference from the identity raw-$B$ action (negative is lower; exact zero is a tie).  Across the six rows, effective has %d negative/%d positive/%d zero differences and local activation has %d negative/%d positive/%d zero differences; neither rule uniformly improves across all seeds under both candidate readings.  Validation minima are separate query-only and value-only enumerations; they are not a full Cartesian per-projection oracle.}"
            % (*effective_signs, *activation_signs),
            "\\label{tab:aslora-baselines}",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\begin{tabular}{ccllll}",
            "\\toprule",
            r"Seed & Candidates & \shortstack[l]{Raw running $B$} & \shortstack[l]{Current effective} & \shortstack[l]{Local activation} & \shortstack[l]{Single-target\\minima} \\",
            "\\midrule",
        ]
    )
    for row in primary_rows:
        baselines = _mapping(row["baselines"], "ASLoRA baselines")
        oracle = _mapping(baselines["validation_loss_oracle"], "validation oracle")
        _require(
            oracle.get("coverage")
            == "componentwise_query_and_value_only_not_full_cartesian",
            "per-projection oracle coverage was overstated",
        )
        components = _mapping(oracle.get("components"), "oracle components")
        oracle_cell = r"\shortstack[l]{%s\\%s}" % (
            _action_tex(_mapping(components["query_only"], "query oracle")["action_key"]),
            _action_tex(_mapping(components["value_only"], "value oracle")["action_key"]),
        )
        lines.append(
            "%d & %s & %s & %s & %s & %s \\\\"
            % (
                int(row["seed"]),
                "Adjacent" if row["candidate_mode"] == "adjacent" else "All pairs",
                stacked_action(_mapping(baselines["raw_B_rule"], "raw B")["action_key"]),
                action_with_loss_delta(
                    baselines["gauge_invariant_current_effective_baseline"],
                    "effective baseline",
                ),
                action_with_loss_delta(
                    baselines["gauge_invariant_current_local_activation_baseline"],
                    "activation baseline",
                ),
                oracle_cell,
            )
        )
    lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table}"])
    return "\n".join(lines) + "\n"


def router_decision_table(summary: Mapping[str, object], source_path: Path) -> str:
    protocol = _mapping(summary.get("protocol"), "router.protocol")
    aggregate = _mapping(summary.get("across_seed"), "router.across_seed")
    rows = sorted(
        _rows(summary.get("seed_rows"), "router.seed_rows"),
        key=lambda row: int(row.get("seed", -1)),
    )
    _require(
        protocol.get("training_seeds") == list(PRIMARY_SEEDS)
        and tuple(int(row.get("seed", -1)) for row in rows) == PRIMARY_SEEDS,
        "router-decision summary must contain seeds 0, 1, and 2",
    )
    found = [row for row in rows if row.get("status") == "completed"]
    not_found = [
        row for row in rows if row.get("status") == "no_partition_changing_gauge_found"
    ]
    _require(
        len(found) == int(aggregate.get("partition_changing_gauge_found_count", -1))
        and len(not_found)
        == int(aggregate.get("partition_changing_gauge_not_found_count", -1)),
        "router-decision search counts are inconsistent",
    )
    _require(
        bool(aggregate.get("primary_claim_supported"))
        == bool(aggregate.get("replicated_measurable_consequence")),
        "router-decision replication flags disagree",
    )
    _require(
        protocol.get("executed_search_families") == ["positive_stochastic"]
        and protocol.get("executed_sensitivity_analyses") == []
        and protocol.get("unexecuted_nonprimary_protocol_amendments")
        == ["signed_local_search", "same_sorted_group_size_multiset_search"],
        "router-decision execution/amendment status is missing or inconsistent",
    )
    _require(
        int(aggregate.get("initialization_dominated_seed_count", -1)) == len(rows)
        and aggregate.get("learned_system_eligibility") is False,
        "the released byte-LM audit must retain its initialization-dominated boundary",
    )
    attempts = {int(row.get("search_attempted", -1)) for row in rows}
    group_budgets = {int(row.get("group_budget", -1)) for row in rows}
    _require(len(attempts) == 1 and len(group_budgets) == 1, "search protocol drifted")

    lines = _header(source_path)
    _require(len(found) == 1, "the current paper table expects one existence witness")
    witness = found[0]
    _require(
        witness.get("decision_evaluations_stored") is True
        and witness.get("gauge_invariant_baselines_stored") is True
        and all(
            row.get("decision_evaluations_stored") is False
            and row.get("gauge_invariant_baselines_stored") is False
            for row in not_found
        ),
        "router-decision evaluation-storage status is inconsistent",
    )
    lines.extend(
        [
            "\\providecommand{\\RouterSearchSuccesses}{%d}" % len(found),
            "\\providecommand{\\RouterSearchSeeds}{%d}" % len(rows),
            "\\providecommand{\\RouterSearchTrials}{%d}" % next(iter(attempts)),
            "\\providecommand{\\RouterGroupBudget}{%d}" % next(iter(group_budgets)),
            "\\providecommand{\\RouterWitnessDeltaBPB}{%.4f}"
            % _finite(witness["delta_bpb"], "witness delta"),
            "\\providecommand{\\RouterWitnessCILower}{%.4f}"
            % _finite(witness["paired_bootstrap_ci_lower"], "witness CI lower"),
            "\\providecommand{\\RouterWitnessCIUpper}{%.4f}"
            % _finite(witness["paired_bootstrap_ci_upper"], "witness CI upper"),
            "\\providecommand{\\RouterWitnessCandidateBPB}{%.4f}"
            % _finite(witness["candidate_fold_bpb"], "witness candidate BPB"),
            "\\providecommand{\\RouterWitnessUnigramBPB}{%.4f}"
            % _finite(witness["unigram_bpb"], "witness unigram BPB"),
            "\\providecommand{\\RouterWitnessKMeansBPB}{%.4f}"
            % _finite(witness["kmeans_bpb"], "witness k-means BPB"),
            "\\providecommand{\\RouterWitnessWardBPB}{%.4f}"
            % _finite(witness["ward_bpb"], "witness Ward BPB"),
            "\\providecommand{\\RouterUnevaluatedSeeds}{%d}" % len(not_found),
            "\\begin{table}[H]",
            "\\centering",
            "\\small",
            "\\setlength{\\tabcolsep}{3pt}",
            "\\caption{Finite same-group-budget partition-fold search at trained, initialization-dominated byte-LM checkpoints.  ``Not found'' means the predeclared finite search exhausted; it is not a non-existence claim.  Fold BPB compares partitions refit from the same effective tensors.  The sole measurable consequence was not replicated under the same search (one witness in three seeds).}",
            "\\label{tab:router-decision}",
            "\\begin{tabular}{@{}clccc@{}}",
            "\\toprule",
            "Seed & Search & Fold BPB ref.$\\to$cand. & $\\Delta$BPB [95\\% CI] & Replicated? \\\\",
            "\\midrule",
        ]
    )
    for row in rows:
        if row.get("status") == "completed":
            fold = "%.3f$\\to$%.3f" % (
                _finite(row["reference_fold_bpb"], "reference BPB"),
                _finite(row["candidate_fold_bpb"], "candidate BPB"),
            )
            delta = "$%s\\;[%s,%s]$" % (
                _signed(row["delta_bpb"], 3),
                _signed(row["paired_bootstrap_ci_lower"], 3),
                _signed(row["paired_bootstrap_ci_upper"], 3),
            )
            status = "found"
        else:
            fold = delta = "--"
            status = "not found"
        lines.append(
            "%d & %s & %s & %s & %s \\\\"
            % (
                int(row["seed"]),
                status,
                fold,
                delta,
                "no (1/3)",
            )
        )
    lines.extend(
        [
            "\\bottomrule",
            "\\end{tabular}",
            "\\end{table}",
        ]
    )
    return "\n".join(lines) + "\n"


def router_decision_detail_table(
    summary: Mapping[str, object], source_path: Path
) -> str:
    """Format search-funnel, router-movement, and baseline appendix details."""

    # Reuse the main formatter's release gates before exposing detail rows.
    router_decision_table(summary, source_path)
    rows = sorted(
        _rows(summary.get("seed_rows"), "router.seed_rows"),
        key=lambda row: int(row.get("seed", -1)),
    )
    found = [row for row in rows if row.get("status") == "completed"]
