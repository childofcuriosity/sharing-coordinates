"""Generate paper macros from the validated response-tomography summary.

This additive generator intentionally leaves the source-attested response
audit and its existing table untouched.  It validates the structured-probing
claim gates before exposing any number to LaTeX.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import math
from pathlib import Path
from typing import Mapping, Optional, Sequence


PROJECT_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_INPUT = PROJECT_ROOT / "results" / "response_tomography_summary.json"
DEFAULT_OUTPUT = (
    PROJECT_ROOT / "paper" / "generated" / "response_tomography_numbers.tex"
)
PRIMARY_SEEDS = (0, 1, 2)


def _require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def _finite(value: object, name: str) -> float:
    number = float(value)
    _require(math.isfinite(number), f"{name} must be finite")
    return number


def _sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def _scientific(value: object, digits: int = 2) -> str:
    number = _finite(value, "scientific value")
    if number == 0.0:
        return "0"
    exponent = int(math.floor(math.log10(abs(number))))
    mantissa = number / (10.0**exponent)
    return f"{mantissa:.{digits}f}\\!\\times\\!10^{{{exponent}}}"


def render(summary: Mapping[str, object], source_path: Path) -> str:
    _require(
        summary.get("format") == "response-tomography-summary-v2",
        "wrong tomography summary format",
    )
    _require(
        summary.get("status")
        == "validated_three_seed_structured_response_tomography",
        "tomography summary is not validated",
    )
    dimensions = summary.get("dimensions")
    aggregate = summary.get("across_seed")
    rows = summary.get("seed_rows")
    sources = summary.get("source_sha256")
    raw_hashes = summary.get("raw_result_sha256")
    _require(isinstance(dimensions, dict), "missing dimensions")
    _require(isinstance(aggregate, dict), "missing across-seed aggregate")
    _require(isinstance(rows, list), "missing seed rows")
    _require(isinstance(sources, dict), "missing source hashes")
    _require(isinstance(raw_hashes, dict), "missing raw-result hashes")
    _require(
        tuple(sorted(int(row["seed"]) for row in rows)) == PRIMARY_SEEDS,
        "tomography summary must contain seeds 0, 1, and 2 exactly once",
    )
    _require(len(raw_hashes) == 3, "tomography summary must attest three raw files")
    _require(
        all(len(str(digest)) == 64 for digest in sources.values())
        and all(len(str(digest)) == 64 for digest in raw_hashes.values()),
        "tomography hash attestation is incomplete",
    )
    required_flags = (
        "all_rank_and_dimension_checks_pass",
        "all_permutation_controls_pass",
        "all_fixed_nonpermutations_distinguished",
    )
    _require(
        all(aggregate.get(flag) is True for flag in required_flags),
        "tomography summary failed a required control",
    )
    probe_count = int(summary.get("probe_count_K", -1))
    depth = int(dimensions.get("depth_L", -1))
    bases = int(dimensions.get("num_bases_K", -1))
    effective_dimension = int(dimensions.get("effective_D", -1))
    _require(
        probe_count == bases == 4
        and depth == 12
        and effective_dimension == 787_712
        and effective_dimension - bases >= depth,
        "released tomography dimensions or probe count drifted",
    )
    reconstruction = _finite(
        aggregate.get("maximum_component_reconstruction_relative_error"),
        "maximum reconstruction error",
    )
    permutation = _finite(
        aggregate.get("maximum_permutation_probe_relative_response_difference"),
        "maximum permutation response difference",
    )
    nonpermutation = _finite(
        aggregate.get("minimum_nonpermutation_probe_relative_response_difference"),
        "minimum nonpermutation response difference",
    )
    _require(reconstruction < 1e-10, "reconstruction gate failed")
    _require(permutation < 1e-12, "permutation-control gate failed")
    _require(nonpermutation > 1e-3, "nonpermutation detection gate failed")

    logical_source = "results/response_tomography_summary.json"
    lines = [
        "% Auto-generated by experiments/generate_response_tomography_latex.py; do not edit.",
        f"% Source: {logical_source}",
        f"% Source SHA256: {_sha256(source_path)}",
        f"\\providecommand{{\\ResponseTomographyProbeCount}}{{{probe_count}}}",
        f"\\providecommand{{\\ResponseTomographyDepth}}{{{depth}}}",
        f"\\providecommand{{\\ResponseTomographyBases}}{{{bases}}}",
        f"\\providecommand{{\\ResponseTomographyDimension}}{{{effective_dimension:,}}}",
        "\\providecommand{\\ResponseTomographyReconstructionMax}"
        f"{{\\ensuremath{{{_scientific(reconstruction)}}}}}",
        "\\providecommand{\\ResponseTomographyPermutationMax}"
        f"{{\\ensuremath{{{_scientific(permutation)}}}}}",
        "\\providecommand{\\ResponseTomographyNonpermutationMin}"
        f"{{{nonpermutation:.4f}}}",
    ]
    return "\n".join(lines) + "\n"


def generate(input_path: Path, output_path: Path) -> None:
    summary = json.loads(input_path.read_text(encoding="utf-8"))
    _require(isinstance(summary, dict), "tomography summary must be a JSON object")
    output_path.parent.mkdir(parents=True, exist_ok=True)
    with output_path.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(render(summary, input_path))


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    return parser


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = build_parser().parse_args(argv)
    generate(args.input, args.output)
    print(f"wrote response tomography LaTeX: {args.output.resolve()}")


if __name__ == "__main__":
    main()
