"""Check source-bound exploratory recovery records and generate their table."""

import argparse
import json
import math

from experiments.run_factor_recovery import ROOT, digest


def summarize():
    rows = []
    for seed in range(3):
        path = ROOT/f'results/factor_recovery/seed{seed}.json'
        r = json.loads(path.read_text())
        if r['format'] != 'factor-recovery-pilot-v1' or r['seed'] != seed:
            raise ValueError('Incorrect pilot identity')
        if (r['dimensions'] != dict(L=12, K=4, D=787712)
                or r['weight_seed'] != 520000 or r['noise_seed'] != 540000+seed
                or (r['tau'], r['eta_z'], r['eta_b']) != (1., 1., 1.)):
            raise ValueError('Pilot protocol mismatch')
        required = {'experiments/run_factor_recovery.py', 'src/response_factor_recovery.py',
                    'experiments/run_autograd_tomography.py', 'src/response_tomography.py',
                    'src/response_identifiability.py', 'src/language.py', 'src/models.py',
                    'research/FACTOR_RECOVERY_PROTOCOL.md'}
        if set(r['source_sha256']) != required:
            raise ValueError('Incomplete pilot source inventory')
        for name, expected in r['source_sha256'].items():
            if digest(ROOT/name) != expected:
                raise ValueError(f'Pilot source mismatch: {name}')
        if digest(ROOT/f'results/checkpoints/language_seed{seed}.pt') != r['checkpoint_sha256']:
            raise ValueError('Pilot checkpoint mismatch')
        records = r['records']
        if [v['relative_noise'] for v in records] != [0., 1e-10, 1e-8, 1e-6, 1e-4]:
            raise ValueError('Incomplete pilot noise grid')
        for v in records:
            if len(v['absolute_noise_norms']) != 4 or not all(math.isfinite(x) and x >= 0 for x in v['absolute_noise_norms']):
                raise ValueError('Invalid pilot noise norms')
            if v['status'] == 'failed':
                if not v.get('error'):
                    raise ValueError('Unexplained pilot failure')
                continue
            if v['status'] != 'ok':
                raise ValueError('Unknown pilot outcome')
            errors = [v[name] for name in ('orbit_relative_error', 'router_relative_error', 'basis_relative_error')]
            if not all(math.isfinite(x) and x >= 0 for x in errors):
                raise ValueError('Invalid pilot errors')
            if not math.isclose(errors[0], math.hypot(*errors[1:]), rel_tol=1e-12):
                raise ValueError('Inconsistent orbit error')
            if sorted(v['evaluation_permutation']) != list(range(4)):
                raise ValueError('Invalid evaluation permutation')
            if not all(math.isfinite(x) for x in v['diagnostics'].values()):
                raise ValueError('Nonfinite recovery diagnostics')
        gate = records[0]['status'] == 'ok' and records[0]['orbit_relative_error'] <= 1e-5
        if r['noiseless_gate'] != gate:
            raise ValueError('Incorrect stored pilot gate')
        # Preserve failures in generated output rather than silently dropping rows.
        rows.append(dict(seed=seed, noiseless_gate=gate, records=records,
                         record_sha256=digest(path)))
    return dict(format='factor-recovery-summary-v1', rows=rows,
                scope='native charts of three existing checkpoints; exact product, fixed random weights, PSD-clipped estimator')


def latex(summary):
    lines = [r'% Generated by experiments/summarize_factor_recovery.py.',
             r'\begin{table}[H]', r'\centering\small',
             r'\caption{Exploratory factor recovery from full-dimensional autodiff observations. Orbit error combines relative router and basis errors after one common permutation. Noisy rows use relative observation noise $10^{-4}$ and no simplex projection.}',
             r'\label{tab:factor-recovery}', r'\begin{tabular}{@{}crrr@{}}', r'\toprule',
             r'Seed & Noiseless orbit error & Noisy orbit error & Noisy row-sum error \\', r'\midrule']
    for row in summary['rows']:
        clean, noisy = row['records'][0], row['records'][-1]
        def value(record, name):
            if record['status'] != 'ok':
                return 'failed'
            number = record.get(name, record['diagnostics'].get(name))
            return f'{number:.2e}'
        lines.append(f"{row['seed']} & {value(clean, 'orbit_relative_error')} & {value(noisy, 'orbit_relative_error')} & {value(noisy, 'router_row_sum_max_error')} " + r'\\')
    return '\n'.join(lines+[r'\bottomrule', r'\end{tabular}', r'\end{table}', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    summary = summarize()
    for path, content in {
        ROOT/'results/factor_recovery/summary.json': json.dumps(summary, indent=2, allow_nan=False)+'\n',
        ROOT/'paper/generated/factor_recovery_table.tex': latex(summary),
    }.items():
        if args.check:
            if path.read_bytes() != content.encode():
                raise SystemExit(f'Stale pilot artifact: {path}')
        else:
            path.write_bytes(content.encode())
    print('factor recovery pilot artifacts checked' if args.check else 'factor recovery pilot artifacts written')


if __name__ == '__main__':
    main()
